"""
state.py: Pydantic v2 execution state schema for EvidenceFlow LangGraph workflow.
Enforces runtime validation on query scope, retrieved passages, citations, and audit trails.
"""

from typing import Any, Dict, List, Optional
from pydantic import BaseModel, Field


class Citation(BaseModel):
    """Structured citation reference pointing to a verified documentation chunk."""
    chunk_id: str
    doc_name: str
    section: str
    quote: str
    is_verified: bool = False


class EvidenceFlowState(BaseModel):
    """
    Central immutable state passing through all LangGraph workflow nodes.
    """
    # --- Input & Scope ---
    query: str = Field(description="The user's original technical question")
    target_version: Optional[str] = Field(default=None, description="Explicit or inferred PostgreSQL version scope (e.g. '14', '15', '16')")
    thread_id: str = Field(default="default_thread", description="Conversation thread identifier for checkpointer")

    # --- Planning & Retrieval ---
    plan: List[str] = Field(default_factory=list, description="Targeted search sub-queries generated by the Planner")
    retrieved_passages: List[Dict[str, Any]] = Field(default_factory=list, description="Passage chunks retrieved from Qdrant with payload metadata")

    # --- Generation & Citations ---
    draft_answer: str = Field(default="", description="The generated technical response containing citation markers [^chunk_id]")
    citations: List[Citation] = Field(default_factory=list, description="Verified citation objects mapped to retrieved chunk IDs")

    # --- Deterministic Verification & Abstention ---
    l1_passed: bool = Field(default=False, description="Whether L1 deterministic citation-existence check passed")
    is_abstained: bool = Field(default=False, description="True if evidence is insufficient or question is out of scope")
    abstention_code: Optional[str] = Field(default=None, description="Categorical refusal code (e.g. INJECTION, OUT_OF_SCOPE, MISSING_KEYWORD, LOW_SCORE, UNSUPPORTED_VERSION, FAKE_CITATION, VALUE_MISMATCH)")
    abstention_reason: Optional[str] = Field(default=None, description="Structured rationale explaining why the system abstained")

    # --- Audit Trail ---
    audit_trail: List[Dict[str, Any]] = Field(default_factory=list, description="Immutable step ledger recording node transitions and metrics")
